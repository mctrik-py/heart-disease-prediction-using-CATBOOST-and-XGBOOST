

"""

pdf_report.py

Generates a professional PDF report for individual patient risk prediction.

"""



from fpdf import FPDF

import pandas as pd

import numpy as np

import matplotlib.pyplot as plt

import shap

import io

from datetime import datetime

import matplotlib
matplotlib.use('Agg')





class HeartDiseaseReport(FPDF):

    """Custom PDF class for heart disease risk prediction reports."""

    

    def header(self):

        self.set_font('Helvetica', 'B', 16)

        self.set_text_color(46, 134, 171)

        self.cell(0, 10, 'Heart Disease Risk Prediction Report', 0, 1, 'C')

        self.ln(2)

        

        self.set_font('Helvetica', 'I', 10)

        self.set_text_color(100, 100, 100)

        self.cell(0, 6, 'Generated by CatBoost + XGBoost Machine Learning Models', 0, 1, 'C')

        self.ln(5)

        

        self.set_draw_color(46, 134, 171)

        self.set_line_width(0.5)

        self.line(10, self.get_y(), 200, self.get_y())

        self.ln(5)

    

    def footer(self):

        self.set_y(-20)

        self.set_font('Helvetica', 'I', 8)

        self.set_text_color(150, 150, 150)

        self.cell(0, 5, f'Page {self.page_no()}', 0, 0, 'C')

        self.ln(3)

        self.cell(0, 5, 'Research prototype only -- NOT for clinical decision-making', 0, 0, 'C')

    

    def section_title(self, title):

        self.set_font('Helvetica', 'B', 13)

        self.set_text_color(46, 134, 171)

        self.cell(0, 8, title, 0, 1, 'L')

        self.ln(2)

    

    def key_value(self, key, value, key_width=70):

        self.set_font('Helvetica', 'B', 10)

        self.set_text_color(60, 60, 60)

        self.cell(key_width, 7, key, 0, 0, 'L')

        self.set_font('Helvetica', '', 10)

        self.cell(0, 7, str(value), 0, 1, 'L')

    

    def add_image_from_fig(self, fig, width=170):

        buf = io.BytesIO()

        fig.savefig(buf, format='png', dpi=150, bbox_inches='tight')

        buf.seek(0)

        

        import tempfile

        with tempfile.NamedTemporaryFile(suffix='.png', delete=False) as tmp:

            tmp.write(buf.read())

            tmp_path = tmp.name

        

        self.image(tmp_path, x=20, w=width)

        self.ln(5)

        

        import os

        os.unlink(tmp_path)





def generate_pdf_report(

    patient_data,

    catboost_proba,

    xgboost_proba,

    catboost_shap_values,

    feature_names,

    catboost_base_value,

    optimal_threshold=0.5,

    output_path='patient_report.pdf'

):

    pdf = HeartDiseaseReport()

    pdf.add_page()

    

    # Section 1: Report Information

    pdf.section_title('1. Report Information')

    pdf.key_value('Report Date:', datetime.now().strftime('%Y-%m-%d %H:%M:%S'))

    pdf.key_value('Report ID:', f"HD-{datetime.now().strftime('%Y%m%d%H%M%S')}")

    pdf.key_value('Model Version:', 'CatBoost + XGBoost (Calibrated)')

    pdf.key_value('Dataset:', 'BRFSS 2015 (253,680 records)')

    pdf.ln(5)

    

    # Section 2: Risk Prediction

    pdf.section_title('2. Risk Prediction Summary')

    

    avg_risk = (catboost_proba + xgboost_proba) / 2

    

    if avg_risk < 0.05:

        risk_category = 'Very Low Risk'

        risk_color = (39, 174, 96)

    elif avg_risk < 0.10:

        risk_category = 'Low Risk'

        risk_color = (46, 204, 113)

    elif avg_risk < 0.20:

        risk_category = 'Moderate Risk'

        risk_color = (241, 196, 15)

    elif avg_risk < 0.35:

        risk_category = 'High Risk'

        risk_color = (230, 126, 34)

    else:

        risk_category = 'Very High Risk'

        risk_color = (231, 76, 60)

    

    pdf.set_font('Helvetica', 'B', 14)

    pdf.set_text_color(*risk_color)

    pdf.cell(0, 10, f'Overall Risk: {avg_risk:.1%} -- {risk_category}', 0, 1, 'L')

    pdf.ln(3)

    

    pdf.set_text_color(60, 60, 60)

    pdf.set_font('Helvetica', '', 11)

    pdf.key_value('CatBoost Probability:', f'{catboost_proba:.1%}')

    pdf.key_value('XGBoost Probability:', f'{xgboost_proba:.1%}')

    pdf.key_value('Decision Threshold:', f'{optimal_threshold:.2f}')

    pdf.key_value('Classification:', 'High Risk' if avg_risk >= optimal_threshold else 'Low Risk')

    pdf.ln(5)

    

    # Section 3: Patient Features

    pdf.add_page()

    pdf.section_title('3. Patient Features')

    

    pdf.set_font('Helvetica', 'B', 10)

    pdf.set_fill_color(46, 134, 171)

    pdf.set_text_color(255, 255, 255)

    pdf.cell(70, 8, 'Feature', 1, 0, 'C', True)

    pdf.cell(40, 8, 'Value', 1, 0, 'C', True)

    pdf.cell(70, 8, 'Feature', 1, 1, 'C', True)

    

    pdf.set_text_color(60, 60, 60)

    pdf.set_font('Helvetica', '', 9)

    

    features = list(patient_data.items())

    for i in range(0, len(features), 2):

        f1_name, f1_val = features[i]

        pdf.set_font('Helvetica', 'B', 9)

        pdf.cell(70, 7, f1_name, 1, 0, 'L')

        pdf.set_font('Helvetica', '', 9)

        pdf.cell(40, 7, str(f1_val), 1, 0, 'C')

        

        if i + 1 < len(features):

            f2_name, f2_val = features[i + 1]

            pdf.set_font('Helvetica', 'B', 9)

            pdf.cell(70, 7, f2_name, 1, 0, 'L')

            pdf.set_font('Helvetica', '', 9)

            pdf.cell(70, 7, str(f2_val), 1, 1, 'C')

        else:

            pdf.cell(70, 7, '', 1, 0, 'L')

            pdf.cell(70, 7, '', 1, 1, 'C')

    

    pdf.ln(5)

    

    # Section 4: SHAP Explanation

    pdf.section_title('4. Feature Contributions (SHAP Explanation)')

    

    pdf.set_font('Helvetica', '', 10)

    pdf.multi_cell(0, 6, 

        'The chart below shows how each feature contributed to this patient\'s '

        'risk prediction. Features pushing the prediction higher (red) increase risk; '

        'features pushing lower (blue) decrease risk.'

    )

    pdf.ln(3)

    

    fig = plt.figure(figsize=(10, 6))

    shap.waterfall_plot(

        shap.Explanation(

            values=catboost_shap_values,

            base_values=catboost_base_value,

            data=np.array(list(patient_data.values())),

            feature_names=list(patient_data.keys())

        ),

        max_display=10,

        show=False

    )

    plt.title(f'SHAP Waterfall -- Patient Risk: {catboost_proba:.1%}', fontsize=12)

    plt.tight_layout()

    

    pdf.add_image_from_fig(fig, width=170)

    plt.close(fig)

    

    # Section 5: Top Contributing Features

    pdf.add_page()

    pdf.section_title('5. Top Contributing Features')

    

    shap_df = pd.DataFrame({

        'Feature': feature_names,

        'SHAP Value': catboost_shap_values,

        'Patient Value': [patient_data[f] for f in feature_names]

    })

    shap_df['Abs SHAP'] = np.abs(shap_df['SHAP Value'])

    shap_df = shap_df.sort_values('Abs SHAP', ascending=False).head(10)

    

    pdf.set_font('Helvetica', 'B', 10)

    pdf.set_fill_color(46, 134, 171)

    pdf.set_text_color(255, 255, 255)

    pdf.cell(60, 8, 'Feature', 1, 0, 'C', True)

    pdf.cell(35, 8, 'Patient Value', 1, 0, 'C', True)

    pdf.cell(45, 8, 'SHAP Value', 1, 0, 'C', True)

    pdf.cell(40, 8, 'Direction', 1, 1, 'C', True)

    

    pdf.set_text_color(60, 60, 60)

    pdf.set_font('Helvetica', '', 9)

    

    for _, row in shap_df.iterrows():

        direction = 'Increases Risk' if row['SHAP Value'] > 0 else 'Decreases Risk'

        color = (231, 76, 60) if row['SHAP Value'] > 0 else (46, 134, 171)

        

        pdf.cell(60, 7, str(row['Feature']), 1, 0, 'L')

        pdf.cell(35, 7, str(row['Patient Value']), 1, 0, 'C')

        pdf.cell(45, 7, f"{row['SHAP Value']:+.4f}", 1, 0, 'C')

        pdf.set_text_color(*color)

        pdf.cell(40, 7, direction, 1, 1, 'C')

        pdf.set_text_color(60, 60, 60)

    

    pdf.ln(5)

    

    # Section 6: Model Performance

    pdf.section_title('6. Model Performance (Test Set)')

    

    pdf.set_font('Helvetica', 'B', 10)

    pdf.set_fill_color(46, 134, 171)

    pdf.set_text_color(255, 255, 255)

    pdf.cell(70, 8, 'Metric', 1, 0, 'C', True)

    pdf.cell(55, 8, 'CatBoost', 1, 0, 'C', True)

    pdf.cell(55, 8, 'XGBoost', 1, 1, 'C', True)

    

    pdf.set_text_color(60, 60, 60)

    pdf.set_font('Helvetica', '', 9)

    

    metrics = [

        ('ROC-AUC', '0.8509', '0.8494'),

        ('PR-AUC', '0.3717', '0.3705'),

        ('Brier Score', '0.0701', '0.0703'),

        ('Recall (Sensitivity)', '0.82', '0.82'),

        ('Precision (PPV)', '0.24', '0.24'),

        ('F1 Score', '0.37', '0.37'),

    ]

    

    for metric, cat_val, xgb_val in metrics:

        pdf.cell(70, 7, metric, 1, 0, 'L')

        pdf.cell(55, 7, cat_val, 1, 0, 'C')

        pdf.cell(55, 7, xgb_val, 1, 1, 'C')

    

    pdf.ln(5)

    

    # Section 7: Clinical Interpretation

    pdf.section_title('7. Clinical Interpretation')

    

    pdf.set_font('Helvetica', '', 10)

    

    interpretation = (

        f"Based on the machine learning analysis, this patient has an estimated "

        f"heart disease risk of {avg_risk:.1%} ({risk_category}). "

    )

    

    if avg_risk >= optimal_threshold:

        interpretation += (

            "The predicted risk exceeds the decision threshold, indicating that "

            "further clinical evaluation and diagnostic testing may be warranted. "

            "The top contributing risk factors are listed in Section 5."

        )

    else:

        interpretation += (

            "The predicted risk is below the decision threshold. Routine preventive "

            "care and lifestyle counseling are recommended, with periodic reassessment."

        )

    

    pdf.multi_cell(0, 6, interpretation)

    pdf.ln(5)

    

    # Section 8: Limitations

    pdf.section_title('8. Important Limitations')

    

    pdf.set_font('Helvetica', '', 9)

    limitations = (

        "* This report is generated by a machine learning model trained on the BRFSS 2015 survey "

        "dataset (253,680 records) and is intended for research purposes only.\n"

        "* The model has NOT been externally validated on independent clinical cohorts.\n"

        "* Predictions are based on self-reported survey data and may not reflect clinical measurements.\n"

        "* This report does NOT constitute medical advice and should NOT replace clinical judgment.\n"

        "* All clinical decisions should be made by qualified healthcare professionals."

    )

    pdf.multi_cell(0, 6, limitations)

    

    pdf.output(output_path)

    print(f"PDF report generated: {output_path}")

    return output_path

